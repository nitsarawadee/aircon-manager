import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

/**
 * ============================================================================
 * ไฟล์แบบฟอร์มแม่แบบ
 * ============================================================================
 *
 * เก็บไฟล์ .xlsx ตัวจริงของแบบฟอร์มควบคุมไว้ให้ระบบหยิบไปเติมข้อมูล
 *
 * ----------------------------------------------------------------------------
 * ทำไมอยู่ที่ assets/forms/ ไม่ใช่ data/
 * ----------------------------------------------------------------------------
 * โฟลเดอร์ data/ ถูกกันไว้ใน .gitignore เพราะเป็นข้อมูลจริงของบริษัท
 * ถ้าเอาไฟล์แม่แบบไปวางตรงนั้น มันจะไม่ขึ้น git แล้วตอนย้ายไปรันเครื่องอื่น
 * ฟอร์มจะหายไปเฉยๆ โดยไม่มีอะไรฟ้องจนกว่าจะมีคนกดโหลด
 *
 * ตัวฟอร์มเปล่าไม่มีข้อมูลลูกค้าอยู่ข้างใน มีแต่หัวตารางกับโลโก้ จึงเก็บรวมไป
 * กับโค้ดได้ และควรเก็บรวมด้วย เพราะมันคือ "ส่วนหนึ่งของระบบ" เหมือนหน้าเว็บ
 * ไม่ใช่ข้อมูลที่ระบบผลิตขึ้น
 *
 * ----------------------------------------------------------------------------
 * ไฟล์ไม่ได้ถูกเสิร์ฟผ่าน URL สาธารณะ
 * ----------------------------------------------------------------------------
 * เหตุผลเดียวกับรูปถ่ายและไฟล์ PDF — ถึงจะเป็นฟอร์มเปล่า แต่มันเป็นเอกสารควบคุม
 * ของบริษัท ไม่ใช่ของที่ควรโหลดได้โดยไม่ต้องล็อกอิน หน้าเว็บจึงต้องขอผ่าน
 * คำสั่งปกติที่มีการตรวจสิทธิ์ เหมือนเอกสารอย่างอื่น
 */

/** แบบฟอร์มที่ระบบรู้จัก — ชื่อสั้นที่ src/ ใช้เรียก → ชื่อไฟล์จริง */
const FORMS = {
  cleaning: 'cleaning-form-template.xlsx',
  repair: 'repair-form-template.xlsx'
};

/**
 * อ่านไฟล์แม่แบบขึ้นมาเป็นก้อนไบต์
 *
 * อ่านใหม่ทุกครั้ง ไม่เก็บไว้ในหน่วยความจำ เพราะไฟล์เล็ก (ราว 38KB)
 * และการอ่านใหม่แปลว่าถ้ามีคนเปลี่ยนไฟล์ฟอร์มเป็น Rev ใหม่
 * ระบบจะใช้ของใหม่ทันทีโดยไม่ต้องรีสตาร์ต
 *
 * @param {string} root โฟลเดอร์รากของโปรเจกต์
 * @param {string} name ชื่อแบบฟอร์ม เช่น 'repair'
 * @returns {Uint8Array}
 */
export function readFormTemplate(root, name) {
  const file = FORMS[name];
  if (!file) throw new Error('ไม่รู้จักแบบฟอร์มชื่อ ' + name);

  const path = join(root, 'assets', 'forms', file);
  if (!existsSync(path)) {
    throw new Error('ไม่พบไฟล์แบบฟอร์ม ' + file + ' — ต้องมีอยู่ที่ assets/forms/');
  }

  return new Uint8Array(readFileSync(path));
}

/** รายชื่อแบบฟอร์มที่มีไฟล์อยู่จริง — ใช้ตอนเปิดเครื่องเพื่อบอกว่าอะไรขาด */
export function missingFormTemplates(root) {
  return Object.entries(FORMS)
    .filter(([, file]) => !existsSync(join(root, 'assets', 'forms', file)))
    .map(([name]) => name);
}
