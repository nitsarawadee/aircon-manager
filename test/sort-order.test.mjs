/**
 * การเรียงรายการใหม่ก่อนเก่า ต้องให้ผลเดิมทุกครั้ง
 *
 * ============================================================================
 * ปัญหาที่ชุดนี้แก้
 * ============================================================================
 * ของเดิมเขียนตัวเปรียบเทียบไว้ว่า (a.Date < b.Date ? 1 : -1)
 * ซึ่งคืน -1 ทั้งสองทิศทางเมื่อค่าเท่ากัน แปลว่ามันบอกว่า "a มาก่อน b" และ
 * "b มาก่อน a" พร้อมกัน ซึ่งขัดแย้งกันเอง
 *
 * ตัวเรียงของ JavaScript ไม่การันตีผลลัพธ์เมื่อเจอตัวเปรียบเทียบแบบนี้
 * รายการที่วันที่ตรงกันจึงสลับที่กันเองได้ทุกครั้งที่โหลด โดยไม่มีอะไรฟ้อง
 *
 * ในข้อมูลจริงเรื่องนี้เกิดแน่ — วันที่ 2026-09-10 วันเดียวมีประวัติซ้อนกัน
 * 22 รายการ และวันที่ 2026-08-25 มี 12 รายการ
 *
 * ============================================================================
 * กติกาที่ล็อกไว้
 * ============================================================================
 * - ใหม่ก่อนเก่า
 * - ค่าเท่ากัน ตัดสินด้วยลำดับที่บันทึกเข้ามา (_row) ใหม่ก่อน
 * - ผลลัพธ์ต้องเหมือนเดิมทุกครั้ง ไม่ว่าจะเรียงกี่รอบ หรือข้อมูลเข้ามาลำดับไหน
 */

import { strict as assert } from 'node:assert';
import test from 'node:test';

import { newestFirst } from '../src/modules/history.js';

/** รายการที่วันที่ซ้ำกันเยอะ แบบเดียวกับข้อมูลจริง */
const many = (count, date) =>
  Array.from({ length: count }, (_, i) => ({ _row: i + 2, ID: 'H' + (i + 1), Date: date }));

test('ค่าเท่ากัน ตัวเปรียบเทียบต้องคืน 0 ไม่ใช่บอกว่ามาก่อนทั้งคู่', () => {
  // นี่คือต้นเหตุทั้งหมด — ตัวเปรียบเทียบที่ขัดแย้งกันเองทำให้ผลเรียงไม่แน่นอน
  const cmp = newestFirst('Date');
  const a = { Date: '2026-09-10', _row: 5 };
  const b = { Date: '2026-09-10', _row: 5 };

  assert.equal(cmp(a, b), 0);
  assert.equal(cmp(b, a), 0);
});

test('เรียงใหม่ก่อนเก่าตามวันที่', () => {
  const list = [
    { _row: 2, ID: 'A', Date: '2026-04-27' },
    { _row: 3, ID: 'B', Date: '2026-09-22' },
    { _row: 4, ID: 'C', Date: '2026-07-03' }
  ];
  assert.deepEqual(list.sort(newestFirst('Date')).map(r => r.ID), ['B', 'C', 'A']);
});

test('วันที่เท่ากัน รายการที่บันทึกทีหลังต้องอยู่บนสุด', () => {
  const list = [
    { _row: 2, ID: 'เก่าสุด', Date: '2026-09-10' },
    { _row: 9, ID: 'ใหม่สุด', Date: '2026-09-10' },
    { _row: 5, ID: 'กลาง', Date: '2026-09-10' }
  ];
  assert.deepEqual(list.sort(newestFirst('Date')).map(r => r.ID), ['ใหม่สุด', 'กลาง', 'เก่าสุด']);
});

test('วันที่ซ้ำกัน 22 รายการ ต้องได้ลำดับเดิมทุกครั้ง', () => {
  // จำนวนนี้ไม่ได้สุ่มมา — วันที่ 2026-09-10 ในข้อมูลจริงมีประวัติ 22 รายการ
  // และตัวเรียงของ V8 เปลี่ยนวิธีทำงานเมื่อรายการยาวเกินระดับหนึ่ง
  const base = many(22, '2026-09-10');
  const want = base.slice().sort(newestFirst('Date')).map(r => r.ID);

  // สลับลำดับที่ป้อนเข้าไปหลายแบบ ผลต้องออกมาเหมือนกันหมด
  const shuffles = [
    base.slice().reverse(),
    base.slice().sort((x, y) => x.ID.localeCompare(y.ID)),
    base.slice(11).concat(base.slice(0, 11))
  ];
  for (const s of shuffles) {
    assert.deepEqual(s.sort(newestFirst('Date')).map(r => r.ID), want,
      'ลำดับต้องไม่ขึ้นกับลำดับที่ข้อมูลเข้ามา');
  }
});

test('เรียงซ้ำหลายรอบ ผลต้องไม่ขยับ', () => {
  let list = many(22, '2026-09-10').concat(many(12, '2026-08-25'));
  const first = list.sort(newestFirst('Date')).map(r => r._row + '|' + r.Date);

  for (let i = 0; i < 3; i++) {
    list = list.sort(newestFirst('Date'));
    assert.deepEqual(list.map(r => r._row + '|' + r.Date), first);
  }
});

test('ค่าว่างหรือไม่มีค่า ต้องไม่ทำให้พัง และไปอยู่ท้ายสุด', () => {
  const list = [
    { _row: 2, ID: 'ว่าง', Date: '' },
    { _row: 3, ID: 'มีวันที่', Date: '2026-09-22' },
    { _row: 4, ID: 'ไม่มีช่อง' }
  ];
  const out = list.sort(newestFirst('Date')).map(r => r.ID);
  assert.equal(out[0], 'มีวันที่');
  assert.deepEqual(out.slice(1).sort(), ['ว่าง', 'ไม่มีช่อง'].sort());
});

test('ใช้กับช่องอื่นได้ด้วย เช่น CreatedAt ของตารางเอกสาร', () => {
  // ใบที่รวมกันถูกเขียนสองแถวในคำสั่งเดียว CreatedAt จึงตรงกันถึงวินาที
  const list = [
    { _row: 2, ID: 'ใบแรก', CreatedAt: '2026-09-22 10:52:36' },
    { _row: 3, ID: 'ใบสอง', CreatedAt: '2026-09-22 10:52:36' },
    { _row: 4, ID: 'ใบเก่า', CreatedAt: '2026-09-15 08:00:00' }
  ];
  assert.deepEqual(list.sort(newestFirst('CreatedAt')).map(r => r.ID), ['ใบสอง', 'ใบแรก', 'ใบเก่า']);
});
