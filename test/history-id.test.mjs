/**
 * ทดสอบเลขรันของรายการประวัติ
 *
 * เลขนี้มีไว้ให้คนอ้างอิงกันด้วยปากเปล่าและในเอกสาร
 * ("รายการ H-0042 คืองานซ่อมตัวนั้น") ความถูกต้องที่สำคัญที่สุดจึงไม่ใช่
 * ความสวยงามของรูปแบบ แต่คือ "เลขหนึ่งเลขต้องหมายถึงรายการเดียวตลอดไป"
 */

import { strict as assert } from 'node:assert';
import test from 'node:test';
import { nextHistoryId } from '../src/modules/history.js';

test('ยังไม่มีประวัติเลย ต้องเริ่มที่ H-0001', () => {
  assert.equal(nextHistoryId([]), 'H-0001');
});

test('นับต่อจากเลขที่มากที่สุด', () => {
  assert.equal(nextHistoryId([{ ID: 'H-0001' }, { ID: 'H-0002' }]), 'H-0003');
});

test('เลขที่ถูกลบไป ต้องไม่ถูกเอากลับมาใช้ซ้ำ', () => {
  // ถ้าเอาเลขเดิมมาใช้ใหม่ เอกสารที่เคยอ้างเลขนั้นจะชี้ไปผิดรายการ
  const rows = [{ ID: 'H-0001' }, { ID: 'H-0005' }];   // 2-4 ถูกลบไปแล้ว
  assert.equal(nextHistoryId(rows), 'H-0006');
});

test('เรียงลำดับตามตัวเลข ไม่ใช่ตามตัวอักษร', () => {
  // ถ้าเทียบแบบข้อความ "H-0009" จะมากกว่า "H-0010" ซึ่งผิด
  assert.equal(nextHistoryId([{ ID: 'H-0009' }, { ID: 'H-0010' }]), 'H-0011');
});

test('เลขเกินสี่หลักต้องยังทำงานได้ ไม่ถูกตัดทิ้ง', () => {
  assert.equal(nextHistoryId([{ ID: 'H-9999' }]), 'H-10000');
});

test('ID รูปแบบเก่าที่เป็นเลขเวลา ต้องถูกข้ามไปไม่เอามาคิด', () => {
  // ถ้าเผลอเอา H1785308032365 มาคิดเป็นตัวเลข เลขถัดไปจะพุ่งไปหลักล้านล้าน
  const rows = [{ ID: 'H1785308032365' }, { ID: 'H-0003' }];
  assert.equal(nextHistoryId(rows), 'H-0004');
});

test('แถวที่ไม่มี ID หรือ ID ว่าง ต้องไม่ทำให้พัง', () => {
  assert.equal(nextHistoryId([{ ID: '' }, {}, { ID: null }, { ID: 'H-0002' }]), 'H-0003');
});

test('ช่องว่างหน้าหลัง ID ต้องไม่ทำให้เลขหาย', () => {
  assert.equal(nextHistoryId([{ ID: '  H-0007  ' }]), 'H-0008');
});
