/**
 * ทดสอบเลขที่เอกสารของรายการประวัติ
 *
 * รูปแบบ <PM|CM><ปี 2 หลัก><เดือน 2 หลัก>-<ลำดับ> เป็นเลขที่ใช้อ้างอิงในเอกสารจริง
 * ความถูกต้องที่สำคัญที่สุดจึงคือ "เลขหนึ่งเลขต้องหมายถึงรายการเดียวตลอดไป"
 * และรูปแบบต้องตรงกับที่ตกลงกันไว้เป๊ะ เพราะมีคนเอาไปใช้อ้างอิงต่อ
 */

import { strict as assert } from 'node:assert';
import test from 'node:test';
import { makeHistoryId, historyPrefix } from '../src/modules/history.js';
import { statusChangeEvent } from '../src/modules/airlist.js';
import { isRetiredStatus } from '../src/values.js';

/* ==================== ตัวอย่างที่ตกลงกันไว้ ==================== */

test('งานล้างแอร์ 3 ก.ย. 2026 งานแรกของเดือน ต้องได้ PM2609-01', () => {
  assert.equal(makeHistoryId('ล้างแอร์', '2026-09-03', []), 'PM2609-01');
});

test('งานซ่อม 19 พ.ย. 2026 ลำดับที่ 123 ต้องได้ CM2611-123', () => {
  // มีงานซ่อมในเดือนนั้นมาแล้ว 122 รายการ
  const existing = Array.from({ length: 122 }, (_, i) => 'CM2611-' + String(i + 1).padStart(2, '0'));
  assert.equal(makeHistoryId('ซ่อม', '2026-11-19', existing), 'CM2611-123');
});

/* ==================== การเลือก PM หรือ CM ==================== */

test('งานที่มีคำว่าล้าง ใช้ PM', () => {
  assert.equal(historyPrefix('ล้างแอร์'), 'PM');
  assert.equal(historyPrefix('ล้างใหญ่'), 'PM');
});

test('งานซ่อม ติดตั้ง แจ้งซ่อม ปลดระวาง ใช้ CM ทั้งหมด', () => {
  for (const t of ['ซ่อม', 'ติดตั้ง', 'แจ้งซ่อม', 'ปลดระวาง', 'เปลี่ยนอะไหล่', 'ย้าย', 'อื่นๆ']) {
    assert.equal(historyPrefix(t), 'CM', t + ' ควรเป็น CM');
  }
});

test('เหตุการณ์ว่างหรือไม่รู้จัก ให้เป็น CM ไม่ใช่พัง', () => {
  assert.equal(historyPrefix(''), 'CM');
  assert.equal(historyPrefix(null), 'CM');
});

/* ==================== การนับลำดับ ==================== */

test('ลำดับนับใหม่ทุกเดือน', () => {
  const existing = ['PM2609-01', 'PM2609-02', 'PM2609-03'];
  assert.equal(makeHistoryId('ล้างแอร์', '2026-10-01', existing), 'PM2610-01', 'เดือนใหม่ต้องเริ่มที่ 01');
  assert.equal(makeHistoryId('ล้างแอร์', '2026-09-20', existing), 'PM2609-04', 'เดือนเดิมต้องนับต่อ');
});

test('PM กับ CM นับแยกกัน', () => {
  const existing = ['PM2609-01', 'PM2609-02'];
  assert.equal(makeHistoryId('ซ่อม', '2026-09-15', existing), 'CM2609-01', 'CM ต้องเริ่มนับของตัวเอง');
});

test('ปีต่างกันต้องนับแยก', () => {
  assert.equal(makeHistoryId('ล้างแอร์', '2027-09-01', ['PM2609-05']), 'PM2709-01');
});

test('เลขที่ถูกลบไป ต้องไม่ถูกเอากลับมาใช้ซ้ำ', () => {
  // ถ้าใช้เลขเดิมซ้ำ เอกสารที่เคยอ้างเลขนั้นจะชี้ไปผิดรายการ
  const existing = ['PM2609-01', 'PM2609-05'];   // 02-04 ถูกลบไปแล้ว
  assert.equal(makeHistoryId('ล้างแอร์', '2026-09-10', existing), 'PM2609-06');
});

test('เรียงลำดับตามตัวเลข ไม่ใช่ตามตัวอักษร', () => {
  // ถ้าเทียบแบบข้อความ "PM2609-09" จะมากกว่า "PM2609-10" ซึ่งผิด
  const existing = ['PM2609-09', 'PM2609-10'];
  assert.equal(makeHistoryId('ล้างแอร์', '2026-09-11', existing), 'PM2609-11');
});

test('ลำดับเกิน 99 ต้องไม่ถูกตัดทิ้ง', () => {
  assert.equal(makeHistoryId('ล้างแอร์', '2026-09-11', ['PM2609-99']), 'PM2609-100');
});

/* ==================== ความทนทาน ==================== */

test('ID รูปแบบเก่าต้องถูกข้าม ไม่เอามาคิดเป็นลำดับ', () => {
  // ถ้าเผลอเอา H-0042 หรือ H1785308032365 มาคิด เลขจะเพี้ยนทันที
  const existing = ['H-0042', 'H1785308032365', 'PM2609-03'];
  assert.equal(makeHistoryId('ล้างแอร์', '2026-09-11', existing), 'PM2609-04');
});

test('รายการวันที่ 1 ของเดือน ต้องไม่ได้เลขเดือนก่อนหน้า', () => {
  // เคยพลาดมาแล้วตอนคำนวณด้วยเวลา UTC
  assert.equal(makeHistoryId('ล้างแอร์', '2026-09-01', []), 'PM2609-01');
  assert.equal(makeHistoryId('ล้างแอร์', '2026-01-01', []), 'PM2601-01');
});

test('ไม่มี ID เดิมเลย ต้องเริ่มที่ 01', () => {
  assert.equal(makeHistoryId('ล้างแอร์', '2026-09-03', []), 'PM2609-01');
  assert.equal(makeHistoryId('ล้างแอร์', '2026-09-03', null), 'PM2609-01');
});

test('ID ว่างหรือ null ปนอยู่ ต้องไม่ทำให้พัง', () => {
  const existing = ['', null, undefined, 'PM2609-02'];
  assert.equal(makeHistoryId('ล้างแอร์', '2026-09-03', existing), 'PM2609-03');
});

/* ==================== สถานะเครื่อง -> ชื่อเหตุการณ์ ==================== */

test('เปลี่ยนสถานะเป็นชำรุด/ปลดระวาง ต้องบันทึกว่า "ปลดระวาง" ไม่ใช่ "อื่นๆ"', () => {
  assert.equal(statusChangeEvent('ชำรุด/ปลดระวาง'), 'รื้อถอน/ปลดระวาง');
  assert.equal(statusChangeEvent('ปลดระวาง'), 'รื้อถอน/ปลดระวาง');
});

test('เปลี่ยนสถานะเป็นรอซ่อม คือขั้น "เริ่มซ่อม" ของเคส', () => {
  // ไม่ใช่ "แจ้งซ่อม" เพราะการแจ้งเกิดตอนที่เครื่องกลายเป็นชำรุด ไม่ใช่ตอนนี้
  // ต้องใช้ชื่อเดียวกับปุ่มในหน้างานซ่อม เพราะเป็นการกระทำเดียวกัน แค่เข้าคนละทาง
  assert.equal(statusChangeEvent('รอซ่อม'), 'เริ่มซ่อม');
});

test('กลับมาใช้งานปกติ ให้ถือว่าซ่อมแล้ว', () => {
  assert.equal(statusChangeEvent('ใช้งานปกติ'), 'ซ่อมแล้ว');
});

test('สถานะที่ระบบไม่รู้จัก ยังตกไปเป็นอื่นๆ', () => {
  assert.equal(statusChangeEvent('รอเปลี่ยนเครื่อง'), 'อื่นๆ');
  assert.equal(statusChangeEvent(''), 'อื่นๆ');
});

test('การปลดระวางต้องได้เลขขึ้นต้นด้วย CM', () => {
  const id = makeHistoryId(statusChangeEvent('ชำรุด/ปลดระวาง'), '2026-09-03', []);
  assert.equal(id, 'CM2609-01');
});

/* ==================== สถานะ 4 แบบที่แยกออกจากกันแล้ว ==================== */

test('ชำรุด กับ ปลดระวาง ต้องเป็นคนละเหตุการณ์', () => {
  // แยกกันเพราะความหมายต่างกัน ชำรุดคือเสียแต่ยังอยู่ในระบบ
  // ปลดระวางคือเลิกใช้ถาวร ถ้ารวมกันจะดูไม่ออกว่าเครื่องไหนยังมีโอกาสกลับมา
  assert.equal(statusChangeEvent('ชำรุด'), 'ชำรุด');
  assert.equal(statusChangeEvent('ปลดระวาง'), 'รื้อถอน/ปลดระวาง');
});

test('ค่าเดิม "ชำรุด/ปลดระวาง" ที่ยังค้างอยู่ ต้องถือเป็นปลดระวาง', () => {
  // สตริงนี้มีทั้งสองคำ ถ้าเช็คผิดลำดับจะได้ "ชำรุด" ซึ่งผิดความหมายเดิม
  assert.equal(statusChangeEvent('ชำรุด/ปลดระวาง'), 'รื้อถอน/ปลดระวาง');
});

/* ==================== การกลับมาใช้งาน เชื่อมกับงานซ่อม ==================== */

test('กลับมาใช้งานปกติ ต้องบันทึกเป็น "ซ่อมแล้ว" ไม่ว่ามาจากสถานะไหน', () => {
  // ยุบรวมจากเดิมที่แยกเป็น "ซ่อมแล้ว" กับ "กลับมาใช้งาน"
  // เพราะสำหรับคนอ่านประวัติมันคือเหตุการณ์เดียวกัน คือเครื่องกลับมาใช้ได้แล้ว
  for (const before of ['รอซ่อม', 'ชำรุด', 'ปลดระวาง', 'ชำรุด/ปลดระวาง', '']) {
    assert.equal(statusChangeEvent('ใช้งานปกติ', before), 'ซ่อมแล้ว');
  }
});

test('แก้สถานะเองในหน้ารายการเครื่อง ต้องได้เหตุการณ์เดียวกับตอนกดปิดงานซ่อม', () => {
  // ผู้ใช้ต้องการให้สองทางนี้บันทึกเหมือนกัน จะได้ไม่ต้องจำว่าทางไหนขึ้นคำว่าอะไร
  assert.equal(statusChangeEvent('ใช้งานปกติ'), 'ซ่อมแล้ว');
});

test('ทุกเหตุการณ์ของวงจรซ่อม ต้องได้เลขขึ้นต้นด้วย CM', () => {
  for (const e of ['แจ้งซ่อม', 'ซ่อมแล้ว', 'ชำรุด', 'ปลดระวาง', 'ติดตั้ง']) {
    assert.equal(historyPrefix(e), 'CM', e + ' ต้องเป็น CM');
  }
});

test('วงจรซ่อมครบรอบ ต้องได้เลขไล่กันในเดือนเดียว', () => {
  // แจ้งซ่อม -> ปิดงาน ทั้งสองเหตุการณ์อยู่เดือนเดียวกัน
  const ids = [];
  const push = (event, date) => ids.push(makeHistoryId(event, date, ids));

  push(statusChangeEvent('รอซ่อม'), '2026-09-05');
  push(statusChangeEvent('ใช้งานปกติ'), '2026-09-08');

  assert.deepEqual(ids, ['CM2609-01', 'CM2609-02']);
});

test('ปิดงานซ่อม กับ แก้สถานะเอง ต้องได้ชื่อเหตุการณ์เดียวกัน', () => {
  // ตอนกดปิดงานในหน้างานซ่อม ระบบฝังชื่อเหตุการณ์ไว้ตรงๆ ใน completeRepairRecord
  // ส่วนตอนแก้สถานะเองมาจาก statusChangeEvent — สองที่นี้ต้องไม่หลุดจากกัน
  // ถ้าใครแก้ที่เดียวแล้วลืมอีกที่ ประวัติจะมีสองคำที่หมายถึงเรื่องเดียวกัน
  assert.equal(statusChangeEvent('ใช้งานปกติ'), 'ซ่อมแล้ว');
});

/* ==================== สถานะที่ออกจากการใช้งานแล้ว ====================
   วงจรของเครื่องจบที่ "รื้อถอน/ปลดระวาง" (ถอดออกจากหน้างาน) แล้วไป "Write off"
   ตอนขายออก เครื่องพวกนี้ยังอยู่ในระบบเพราะต้องเก็บประวัติ แต่ต้องไม่ถูกนับ
   เป็นของที่ยังมีอยู่ ไม่งั้นยอดรวมจะบวมทุกปี และแผนล้างจะสั่งไปล้างเครื่องที่ไม่มีแล้ว
   ============================================================================ */

test('สถานะที่ถือว่าออกจากการใช้งานแล้ว', () => {
  assert.equal(isRetiredStatus('รื้อถอน/ปลดระวาง'), true);
  assert.equal(isRetiredStatus('Write off'), true);
  assert.equal(isRetiredStatus('write-off'), true, 'พิมพ์ต่างกันเล็กน้อยก็ต้องจับได้');
  assert.equal(isRetiredStatus('WRITE OFF'), true);
});

test('ชื่อสถานะแบบเก่าที่ยังค้างในข้อมูล ต้องยังถือว่าออกจากการใช้งานแล้ว', () => {
  // ข้อมูลที่ย้ายมาจากชีตเดิมบางแถวยังใช้ชื่อเก่าอยู่ ถ้าไม่รองรับจะกลับไปถูกนับใหม่
  assert.equal(isRetiredStatus('ปลดระวาง'), true);
  assert.equal(isRetiredStatus('ชำรุด/ปลดระวาง'), true);
});

test('สถานะที่ยังใช้งานอยู่ ต้องไม่ถูกนับว่าออกจากระบบ', () => {
  assert.equal(isRetiredStatus('ใช้งานปกติ'), false);
  assert.equal(isRetiredStatus('ชำรุด'), false, 'เสียแต่ยังอยู่หน้างาน ยังต้องนับ');
  assert.equal(isRetiredStatus('รอซ่อม'), false);
  assert.equal(isRetiredStatus(''), false);
  assert.equal(isRetiredStatus(null), false);
});

test('เปลี่ยนสถานะเป็นรื้อถอนหรือ Write off ต้องได้เหตุการณ์คนละอัน', () => {
  // เป็นคนละขั้นของวงจรเดียวกัน ถ้าบันทึกเป็นอันเดียวกันจะแยกไม่ออกว่า
  // เครื่องถูกถอดออกมาแล้วหรือขายออกไปแล้ว
  assert.equal(statusChangeEvent('รื้อถอน/ปลดระวาง'), 'รื้อถอน/ปลดระวาง');
  assert.equal(statusChangeEvent('Write off'), 'Write off');
  assert.equal(statusChangeEvent('ปลดระวาง'), 'รื้อถอน/ปลดระวาง', 'ชื่อเก่าต้องยังจับได้');
});

test('ทุกเหตุการณ์ของขาออกต้องได้เลขขึ้นต้นด้วย CM', () => {
  for (const s of ['รื้อถอน/ปลดระวาง', 'Write off']) {
    assert.equal(historyPrefix(statusChangeEvent(s)), 'CM', 'สถานะ ' + s);
  }
});
